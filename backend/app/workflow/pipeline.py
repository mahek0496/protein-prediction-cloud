"""The protein workflow: A -> B -> (C, D, E, F, G, H in parallel) -> I -> upload to storage."""
import json
import logging
import time
import uuid
from concurrent.futures import ThreadPoolExecutor

from .. import database as db
from ..config import settings
from ..services import analysis
from ..services.features import build_feature_vector
from ..services.report import build_markdown_report
from ..services.sequence import validate_sequence
from ..services.storage import get_storage
from ..services.structure_engine import PredictionSkipped, predict_structure
from .dag import TaskSkipped, TaskSpec, now_iso, run_dag

log = logging.getLogger("workflow")
PARALLEL_IDS = ["C", "D", "E", "F", "G", "H"]


# ---------- task functions (each receives the shared context) ----------
def task_a(ctx):
    res = validate_sequence(ctx["sequence"], settings.min_sequence_length, settings.max_sequence_length)
    res.update(result_type="calculation", method="Input validation + amino-acid composition",
               summary=f"Valid protein sequence of {res['length']} residues.")
    return res


def task_b(ctx):
    res = build_feature_vector(ctx["sequence"])
    res.update(result_type="calculation", method="Composition (20) + physicochemical (11) features",
               summary=f"Created a {res['dimension']}-dimensional numerical feature vector.")
    return res


def _local_analysis(func):
    def run(ctx):
        delay = ctx.get("demo_delay_seconds", 0) or 0
        if delay > 0:
            time.sleep(delay)  # ARTIFICIAL delay, only so the parallel speed-up is visible on screen
        res = func(ctx["sequence"])
        res["artificial_delay_seconds"] = delay
        return res
    return run


def task_h(ctx):
    try:
        return predict_structure(ctx["sequence"])
    except PredictionSkipped as exc:
        raise TaskSkipped(str(exc))


def task_i(ctx):
    out, states = ctx["outputs"], ctx["states"]
    analyses = {}
    for tid in PARALLEL_IDS[:-1]:
        analyses[tid] = out.get(tid) or {"error": states[tid]["error"], "status": states[tid]["status"]}
    if "H" in out:
        structure = {k: v for k, v in out["H"].items() if k != "_files"}
    else:
        structure = {"available": False, "status": states["H"]["status"],
                     "reason": states["H"]["error"] or "Structure prediction did not run."}
    disclosures = [
        "Tasks D and F are deterministic calculations from the sequence.",
        "Task C is an empirical secondary-structure propensity estimate (Chou-Fasman style), NOT a 3D prediction.",
        "Tasks E and G are rule-based screens that flag candidate regions/sites only.",
    ]
    if structure.get("available"):
        disclosures.append(f"Task H 3D model was generated by {structure['engine']}; "
                           "confidence (pLDDT) comes from that model. Not experimentally determined.")
    else:
        disclosures.append("No 3D structure prediction is available for this run, so no structure "
                           "coordinates are shown or stored.")
    delay = ctx.get("demo_delay_seconds", 0)
    if delay:
        disclosures.append(f"An ARTIFICIAL delay of {delay}s was added to each of tasks C-G for demonstration.")
    return {
        "result_type": "report",
        "summary": f"Combined {sum(1 for t in PARALLEL_IDS if states[t]['status'] == 'completed')}"
                   f"/{len(PARALLEL_IDS)} analysis results into the final report.",
        "report": {
            "job_id": ctx["job_id"], "name": ctx["name"], "sequence": ctx["sequence"],
            "length": len(ctx["sequence"]), "generated_at": now_iso(),
            "sequence_analysis": out.get("A"), "features": out.get("B"),
            "analyses": analyses, "structure": structure,
            "task_summaries": [{"id": t, "name": states[t]["name"], "status": states[t]["status"],
                                "result_type": (out.get(t) or {}).get("result_type"),
                                "summary": (out.get(t) or {}).get("summary"), "error": states[t]["error"]}
                               for t in ["A", "B", *PARALLEL_IDS]],
            "disclosures": disclosures,
        },
    }


def task_upload(ctx):
    report = ctx["outputs"]["I"]["report"]
    files = {"report.json": json.dumps(report, indent=2), "report.md": build_markdown_report(report)}
    files.update((ctx["outputs"].get("H") or {}).get("_files", {}))
    saved = get_storage().save_files(ctx["job_id"], files)
    ctx["upload_result"].update(saved)
    backends = sorted({f["backend"] for f in saved["files"]})
    msg = f"Stored {len(saved['files'])} file(s) in {' + '.join(b.upper() for b in backends)}."
    if saved["errors"]:
        msg += f" {len(saved['errors'])} warning(s): S3 upload problem, see storage errors."
    return {"result_type": "storage", "summary": msg}


def build_specs():
    return [
        TaskSpec("A", "Sequence validation & analysis", task_a, [], "sequential",
                 "Validates letters/length, computes composition"),
        TaskSpec("B", "Numerical feature vector", task_b, ["A"], "sequential",
                 "Composition + physicochemical features"),
        TaskSpec("C", "Secondary-structure propensity", _local_analysis(analysis.secondary_structure_propensity),
                 ["B"], "parallel", "Chou-Fasman style empirical estimate"),
        TaskSpec("D", "Physicochemical profile", _local_analysis(analysis.physicochemical_profile),
                 ["B"], "parallel", "MW, pI, GRAVY, instability (ProtParam)"),
        TaskSpec("E", "Hydropathy & TM screen", _local_analysis(analysis.hydropathy_transmembrane),
                 ["B"], "parallel", "Kyte-Doolittle profile"),
        TaskSpec("F", "Charge profile", _local_analysis(analysis.charge_profile),
                 ["B"], "parallel", "Net charge vs pH"),
        TaskSpec("G", "Motif & complexity scan", _local_analysis(analysis.motif_scan),
                 ["B"], "parallel", "N-glycosylation, cysteines, low complexity"),
        TaskSpec("H", "3D structure prediction (ESMFold)", task_h, ["B"], "parallel",
                 "Remote ESMFold model, pLDDT confidence"),
        TaskSpec("I", "Final report", task_i, PARALLEL_IDS, "sequential",
                 "Waits for C-H and combines results", tolerate_failed_deps=True),
        TaskSpec("UPLOAD", "Store results (S3 / local)", task_upload, ["I"], "storage",
                 "Uploads report + structure files"),
    ]


def initial_tasks():
    """Task list in 'pending' state, shown before the workflow starts."""
    return {s.id: {"id": s.id, "name": s.name, "group": s.group, "description": s.description,
                   "depends_on": s.depends_on, "status": "pending", "duration_seconds": None, "error": None,
                   "summary": None, "result_type": None, "start_offset": None, "end_offset": None}
            for s in build_specs()}


def stage_metrics(states: dict, wall: float, mode: str, workers: int, delay: float) -> dict:
    par = [states[t] for t in PARALLEL_IDS if states[t]["duration_seconds"] is not None]
    stage_wall = (max(s["end_offset"] for s in par) - min(s["start_offset"] for s in par)) if par else 0
    stage_sum = sum(s["duration_seconds"] for s in par)
    return {
        "execution_mode": mode, "workers": workers, "total_wall_seconds": wall,
        "parallel_stage_wall_seconds": round(stage_wall, 4),
        "parallel_stage_sum_seconds": round(stage_sum, 4),
        "speedup_vs_sum": round(stage_sum / stage_wall, 2) if stage_wall > 0 else None,
        "artificial_delay_seconds": delay,
        "task_durations": {t: s["duration_seconds"] for t, s in states.items()},
    }


# ---------- job execution ----------
_job_pool = ThreadPoolExecutor(max_workers=max(1, settings.max_concurrent_jobs), thread_name_prefix="job")


def create_and_submit(name: str, sequence: str, mode: str, delay: float) -> str:
    job_id = uuid.uuid4().hex
    db.create_job({"id": job_id, "name": name, "sequence": sequence, "status": "queued",
                   "execution_mode": mode, "demo_delay_seconds": delay, "created_at": now_iso(),
                   "tasks": initial_tasks(), "files": [], "storage_errors": []})
    _job_pool.submit(run_job, job_id)
    return job_id


def run_job(job_id: str):
    job = db.get_job(job_id)
    if not job:
        return
    mode = job["execution_mode"]
    workers = 1 if mode == "sequential" else settings.parallel_workers
    db.update_job(job_id, status="running", started_at=now_iso())
    ctx = {"job_id": job_id, "name": job["name"], "sequence": job["sequence"],
           "demo_delay_seconds": job["demo_delay_seconds"] or 0, "upload_result": {"files": [], "errors": []}}
    try:
        res = run_dag(build_specs(), ctx, workers, on_update=lambda s: db.update_job(job_id, tasks=s))
        states = res["states"]
        report = (res["outputs"].get("I") or {}).get("report")
        upload = ctx["upload_result"]
        if states["A"]["status"] != "completed":
            status, error = "failed", states["A"]["error"]
        elif report is None:
            status, error = "failed", states["I"]["error"] or "Final report could not be produced."
        else:
            status = "completed"
            error = states["UPLOAD"]["error"]  # report exists even if storage failed
        db.update_job(job_id, status=status, error=error, finished_at=now_iso(), tasks=states,
                      total_seconds=res["wall_seconds"], result=report, files=upload["files"],
                      storage_errors=upload["errors"],
                      metrics=stage_metrics(states, res["wall_seconds"], mode, workers, ctx["demo_delay_seconds"]))
    except Exception as exc:  # last-resort guard so a job never stays 'running'
        log.exception("Job %s crashed", job_id)
        db.update_job(job_id, status="failed", error=f"Internal error: {exc}", finished_at=now_iso())


def run_benchmark(sequence: str, delay: float) -> dict:
    """Run tasks C-G (local analyses) twice: sequentially, then in parallel, and compare.

    Task H (remote ESMFold) is excluded so the benchmark does not call the external API twice.
    """
    base = {"sequence": sequence, "demo_delay_seconds": delay}
    local_specs = [s for s in build_specs() if s.id in PARALLEL_IDS[:-1]]
    for s in local_specs:
        s.depends_on = []
    runs = {}
    for mode, workers in (("sequential", 1), ("parallel", len(local_specs))):
        r = run_dag(local_specs, dict(base), workers)
        runs[mode] = {"wall_seconds": r["wall_seconds"], "workers": workers,
                      "tasks": {t: {"duration_seconds": s["duration_seconds"], "start_offset": s["start_offset"],
                                    "end_offset": s["end_offset"], "status": s["status"]}
                                for t, s in r["states"].items()}}
    seq_t, par_t = runs["sequential"]["wall_seconds"], runs["parallel"]["wall_seconds"]
    return {"tasks_benchmarked": [s.id for s in local_specs], "artificial_delay_seconds": delay,
            "runs": runs, "speedup": round(seq_t / par_t, 2) if par_t > 0 else None,
            "note": "Task H (remote ESMFold) excluded. Without an artificial delay, C-G take only "
                    "milliseconds, so thread overhead can make parallel equal or slower."}
